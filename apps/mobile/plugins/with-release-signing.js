/**
 * Signs release builds with MedOS's own keystore instead of the debug key.
 *
 * Why this matters more here than in a typical app: Android refuses to install
 * an update signed with a different key, and the only way out is uninstalling —
 * which deletes the app's private storage. In MedOS that storage IS the
 * database. A release build signed with a machine-specific debug key therefore
 * means a new laptop or a reinstalled Windows makes every future update a
 * data-wiping event.
 *
 * The keystore lives in `<repo>/private/` (gitignored) and is described by
 * `private/keystore.properties`. When that file is absent, release builds fall
 * back to the debug key so a fresh checkout still compiles.
 *
 * `android/` is regenerated by `expo prebuild --clean`, so this has to be a
 * config plugin rather than a hand edit.
 */
const { withAppBuildGradle } = require('expo/config-plugins');

const MARKER = 'medosReleaseSigning';

const PROPS_LOADER = `
// ${MARKER}: release keystore is described by <repo>/private/keystore.properties
def medosKeystorePropsFile = new File(rootProject.projectDir, "../../../private/keystore.properties")
def medosKeystoreProps = new Properties()
if (medosKeystorePropsFile.exists()) {
    medosKeystorePropsFile.withInputStream { medosKeystoreProps.load(it) }
}
`;

const RELEASE_SIGNING_CONFIG = `signingConfigs {
        release {
            if (medosKeystorePropsFile.exists()) {
                storeFile new File(medosKeystorePropsFile.parentFile, medosKeystoreProps['storeFile'])
                storePassword medosKeystoreProps['storePassword']
                keyAlias medosKeystoreProps['keyAlias']
                keyPassword medosKeystoreProps['keyPassword']
            }
        }`;

// The release buildType in the Expo template is the only place these two
// comment lines appear, which makes them a safer anchor than the bare
// `signingConfig signingConfigs.debug` line that the debug buildType shares.
const RELEASE_BUILDTYPE_ANCHOR =
  /\/\/ Caution! In production, you need to generate your own keystore file\.\s*\n\s*\/\/ see https:\/\/reactnative\.dev\/docs\/signed-apk-android\.\s*\n(\s*)signingConfig signingConfigs\.debug/;

function applyReleaseSigning(contents) {
  if (contents.includes(MARKER)) return contents;

  if (!/^android\s*\{/m.test(contents)) {
    throw new Error(`[${MARKER}] could not find the "android {" block in app/build.gradle`);
  }
  if (!/signingConfigs\s*\{/.test(contents)) {
    throw new Error(`[${MARKER}] could not find "signingConfigs {" in app/build.gradle`);
  }
  if (!RELEASE_BUILDTYPE_ANCHOR.test(contents)) {
    // Failing loudly is deliberate. Silently leaving release on the debug key
    // is exactly the data-loss trap this plugin exists to prevent.
    throw new Error(
      `[${MARKER}] the Expo template changed and the release signingConfig line was not found. ` +
        'Update plugins/with-release-signing.js before building a release APK.',
    );
  }

  return contents
    .replace(/^android\s*\{/m, `${PROPS_LOADER}\nandroid {`)
    .replace(/signingConfigs\s*\{/, RELEASE_SIGNING_CONFIG)
    .replace(
      RELEASE_BUILDTYPE_ANCHOR,
      (_match, indent) =>
        // No silent fallback to the debug key: an APK signed with a different
        // key cannot update the installed app without uninstalling it, and
        // that deletes the patient database. Gradle stops instead — including
        // when the build was started from Android Studio rather than npm.
        `// MedOS: the release build is signed with the project's own key, or not at all.\n` +
        `${indent}if (!medosKeystorePropsFile.exists()) {\n` +
        `${indent}    throw new GradleException("MedOS: private/keystore.properties is missing. " +\n` +
        `${indent}        "A release signed with any other key cannot update the installed app " +\n` +
        `${indent}        "without uninstalling it, which deletes the patient database. " +\n` +
        `${indent}        "Restore the private/ folder from your backup.")\n` +
        `${indent}}\n` +
        `${indent}signingConfig signingConfigs.release`,
    );
}

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error(`[${MARKER}] expected a Groovy build.gradle, got ${cfg.modResults.language}`);
    }
    cfg.modResults.contents = applyReleaseSigning(cfg.modResults.contents);
    return cfg;
  });
};

module.exports.applyReleaseSigning = applyReleaseSigning;
